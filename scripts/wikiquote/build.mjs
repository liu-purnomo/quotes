// Turns reviewed translations into src/data/quotes/terjemahan.ts.
// Usage: node scripts/wikiquote/build.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(HERE, '../../src/data/quotes/terjemahan.ts');

const queue = readFileSync(join(HERE, 'queue.jsonl'), 'utf8').trim().split('\n').map((line) => JSON.parse(line));
const translations = JSON.parse(readFileSync(join(HERE, 'translations.json'), 'utf8'));

// Matches the spelling already used by the rest of the dataset
const AUTHOR_NAMES = {
  Aristotle: 'Aristoteles',
  Confucius: 'Kong Hu Cu',
  Laozi: 'Lao Zi',
  'Seneca the Younger': 'Seneca',
  Rumi: 'Jalaluddin Rumi',
  'Abu Hamid al-Ghazali': 'Al-Ghazali',
  'Tenzin Gyatso, 14th Dalai Lama': 'Dalai Lama',
  Napoleon: 'Napoleon Bonaparte',
  'Anthony Robbins': 'Tony Robbins',
  'Alexander the Great': 'Aleksander Agung',
  Epicurus: 'Epikuros',
  Heraclitus: 'Herakleitos',
  'Thomas Aquinas': 'Thomas Aquinas',
  'Augustine of Hippo': 'Agustinus dari Hippo',
  'Pope Francis': 'Paus Fransiskus',
  'Pope John Paul II': 'Paus Yohanes Paulus II',
  Mencius: 'Mensius',
  Saadi: 'Saadi Shirazi',
};

const CATEGORY_RULES = [
  ['perempuan', /perempuan|seorang ibu/i],
  ['kepemimpinan', /pemimpin|manajer|tiran|kekuasaan|berkuasa/i],
  ['nasionalisme', /negara|demokrasi|kemerdekaan|pemerintah|kebebasan|bangsa|hukum|pers\b/i],
  ['pendidikan', /belajar|mempelajari|pengajaran|murid|buku|pengetahuan|ilmu|sains|rasa ingin tahu/i],
  ['seni', /seni|sastra|puisi|menulis|fiksi|cerita/i],
  ['spiritual', /tuhan|agama|berdoa|malaikat|jiwa|nurani/i],
  ['cinta', /\bcinta|mencinta|sahabat|teman/i],
  ['bisnis', /bisnis|pelanggan|pasar saham|percetakan/i],
  ['motivasi', /keberanian|kesulitan|bakat|kejeniusan|bertahan|berkembang|ambisi|menyerah|ilusi|batasan/i],
];

const escape = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const MAX_CITATION = 240; // extract.mjs cuts citations at this length

function cleanCitation(raw) {
  const text = raw
    .replace(/\{\{ISBN\|([^}]*)\}\}/gi, 'ISBN $1')
    .replace(/\{\{[^}]*(\}\}?|$)/g, '')
    .replace(/<[^>]*>?/g, ' ')
    .replace(/&[a-z]+;/g, ' ')
    .replace(/\[?https?:\S+\s*/g, '')
    .replace(/[[\]]/g, '')
    .replace(/&mdash;/g, '—')
    .replace(/\s+/g, ' ')
    .trim();
  return raw.length >= MAX_CITATION ? `${text}…` : text;
}

const seen = new Set();
const entries = translations.map(({ i, text }) => {
  const row = queue[i];
  if (!row) throw new Error(`No queue row ${i}`);
  if (seen.has(i)) throw new Error(`Duplicate queue row ${i}`);
  seen.add(i);

  return {
    text,
    author: AUTHOR_NAMES[row.author] ?? row.author,
    category: CATEGORY_RULES.find(([, pattern]) => pattern.test(text))?.[0] ?? 'kehidupan',
    source: `https://en.wikiquote.org/wiki/${encodeURIComponent(row.author.replace(/ /g, '_'))}`,
    original: row.text.replace(/&mdash;/g, '—'),
    citation: cleanCitation(row.citation),
  };
});

// Quote IDs come from array position, so published entries must never move:
// keep the current file order and only append what is new
const published = existsSync(OUTPUT)
  ? [...readFileSync(OUTPUT, 'utf8').matchAll(/^ {4}original: '((?:\\.|[^'\\])*)',$/gm)]
      .map((match) => match[1].replace(/\\(.)/g, '$1'))
  : [];
const position = new Map(published.map((original, index) => [original, index]));
const rank = (entry) => position.get(entry.original) ?? Number.MAX_SAFE_INTEGER;

entries.sort((a, b) => rank(a) - rank(b));

const body = entries
  .map((entry) => `  {\n${Object.entries(entry).map(([key, value]) => `    ${key}: ${escape(value)},`).join('\n')}\n  },`)
  .join('\n');

writeFileSync(OUTPUT, `// Generated by scripts/wikiquote/build.mjs, edit translations.json instead.
// Sourced quotes from English Wikiquote (https://en.wikiquote.org), CC BY-SA 4.0.
// \`text\` is our Indonesian translation by meaning; \`original\` holds the English text.
export const terjemahan = [
${body}
];
`);

console.log('written', entries.length, 'authors', new Set(entries.map((e) => e.author)).size);
const counts = {};
for (const entry of entries) counts[entry.category] = (counts[entry.category] ?? 0) + 1;
console.log(counts);
