// Turns reviewed Wikimedia candidates into src/data/authorPhotos.ts.
// Usage: node scripts/author-photos/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(HERE, '../../src/data/authorPhotos.ts');

// Same name, different person: the quotes are by the academic, not the pageant winner
const WRONG_PERSON = new Set(['Ayu Saraswati']);

const candidates = JSON.parse(readFileSync(join(HERE, 'candidates.json'), 'utf8'));
const escape = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const shorten = (value) => (value.length > 80 ? `${value.slice(0, 79).trim()}…` : value);

const entries = candidates
  .filter((row) => !WRONG_PERSON.has(row.author))
  .map((row) => `  ${escape(row.author)}: {
    url: ${escape(row.url)},
    page: ${escape(row.page)},
    license: ${escape(row.license)},
    artist: ${escape(shorten(row.artist) || 'Wikimedia Commons')},
  },`);

writeFileSync(OUTPUT, `// Generated by scripts/author-photos/build.mjs from Wikidata and Wikimedia Commons.
// Every image is public domain or openly licensed; credit is shown with the photo.
export interface AuthorPhoto {
  url: string;
  page: string;
  license: string;
  artist: string;
}

export const authorPhotos: Record<string, AuthorPhoto> = {
${entries.join('\n')}
};
`);

console.log('written', entries.length);
